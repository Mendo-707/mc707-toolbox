/** The bank letter of a Wave Group ID ('' when it is not one of the built-in banks). */
export const waveBank = gid => ({ 8: 'A', 10: 'B', 11: 'C' })[gid] || '';
const BANKS = { A: BANK_A, B: BANK_B, C: BANK_C };
/** A built-in wave's name, or '' when the bank or number is not known. */
export function waveName(gid, n) {
  const b = BANKS[waveBank(gid)];
  return (b && b[n - 1]) || '';
}
/** A PCM-Sync wave's name, or ''. */
export const syncWaveName = n => BANK_SYNC[n - 1] || '';
/** How a wave reads: "A 492 MplLmtr Kick", or "Wave 492" when its name is not known. */
export function waveLabel(gtype, gid, n) {
  const name = !gtype ? waveName(gid, n) : '';
  return name ? waveBank(gid) + ' ' + n + ' ' + name : 'Wave ' + n;
}

/* where the sound being edited keeps its values, so a wave number's text can name its wave */
let SRC = () => undefined;
/** The editor's values getter (key -> value). */
export function waveSource(fn) {
  SRC = fn;
}
/** The value text for a wave number or group key, with the wave's name ('' when it has none). */
export function waveText(key, v) {
  const m = /^PTL(\d)\.(WAV_NUM_[LR]|WAV_GID)$/.exec(key);
  if (m) {
    const i = m[1];
    if (m[2] === 'WAV_GID') return waveBank(v) ? 'Bank ' + waveBank(v) + ' (' + v + ')' : '';
    if (!v) return '';
    const gtype = SRC('PTL' + i + '.WAV_GTYPE') || 0,
      gid = SRC('PTL' + i + '.WAV_GID') ?? 8;
    const name = !gtype ? waveName(gid, v) : '';
    return name ? v + ' ' + name : '';
  }
  if (/^SPTL\d\.SYNC_WAV_NUM$/.test(key)) {
    const name = syncWaveName(v);
    return name ? v + ' ' + name : '';
  }
  return '';
}
