// Builds src/core/mpj-templates.js from Roland's empty MC-707 projects (templates/MC707-Project-Templates.zip):
// the project with no drum tracks, gzipped, and for each other layout the bytes that differ from it, so the
// app can start a project file (core/mpj-write.js) from the template for any Track setup.
//   node scripts/mpj-templates.mjs
// Needs unzip. Run it again only if the templates change.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import zlib from 'node:zlib';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'mpj-'));
execFileSync('unzip', ['-q', '-o', path.join(ROOT, 'templates/MC707-Project-Templates.zip'), '-d', tmp]);
const read = n => fs.readFileSync(path.join(tmp, n + ' Drum ' + (8 - n) + ' Tone Tracks.mpj'));
const base = read(0);
/* the differences from the base: [offset u32, length u16, bytes] runs */
function diff(b) {
  const parts = [];
  for (let i = 0; i < base.length; ) {
    if (base[i] === b[i]) {
      i++;
      continue;
    }
    let j = i;
    /* runs joined across short equal stretches, so there are fewer of them */
    while (
      j < base.length &&
      (base[j] !== b[j] || (j + 4 < base.length && base.subarray(j, j + 4).compare(b.subarray(j, j + 4)) !== 0))
    )
      j++;
    const len = Math.min(j - i, 0xffff),
      h = Buffer.alloc(6);
    h.writeUInt32LE(i, 0);
    h.writeUInt16LE(len, 4);
    parts.push(h, b.subarray(i, i + len));
    i += len;
  }
  return Buffer.concat(parts);
}
const gz = b => zlib.gzipSync(b, { level: 9 }).toString('base64');
const layouts = {};
for (const n of [1, 2, 3, 4, 6, 8]) layouts[n] = gz(diff(read(n)));
fs.rmSync(tmp, { recursive: true, force: true });
const out = `// GENERATED by scripts/mpj-templates.mjs from Roland's empty MC-707 projects: do not edit.
// BASE: the project with 8 tone tracks (gzipped, base64). DIFF[n]: the project with n drum tracks first, as
// the bytes that differ from BASE ([offset u32, length u16, bytes] runs, gzipped, base64).
//
// Plain data only. Reads: nothing.
export const MPJ_SIZE = ${base.length};
export const BASE = '${gz(base)}';
export const DIFF = ${JSON.stringify(layouts, null, 1)};
`;
fs.writeFileSync(path.join(ROOT, 'src/core/mpj-templates.js'), out);
console.log('Wrote src/core/mpj-templates.js (' + Math.round(out.length / 1024) + ' KB)');
