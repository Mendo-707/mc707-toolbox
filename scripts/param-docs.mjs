// Writes docs/ZENCORE-PARAMETERS.md, the reference for every ZEN-Core tone, drum kit and MFX parameter
// the editor uses, from the editor's own tables (src/zen/zc-data.js, zc-tone.js, zc-mfx-data.js), so the
// document always matches the code.
//
//   node scripts/param-docs.mjs           update the document
//   node scripts/param-docs.mjs --check   fail if it is out of date (part of npm run check)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DOC = path.join(ROOT, 'docs', 'ZENCORE-PARAMETERS.md');
/* the zen modules read `window` (the Windows app's bridge) when they load; outside a browser there is none */
globalThis.window = globalThis.window || {};
const mod = f => import(pathToFileURL(path.join(ROOT, 'src', 'zen', f)).href);
const { ZC_BLOCKS } = await mod('zc-data.js');
const { LAYOUT } = await mod('zc-tone.js');
const { mfxNames, mfxParams, NOTES } = await mod('zc-mfx.js');

const h2 = n => n.toString(16).toUpperCase().padStart(2, '0');
/* a linear (7-bit) byte count as the 4-byte address offset Roland uses */
const addr = l => [21, 14, 7, 0].map(s => h2((l >> s) & 127)).join(' ');
const esc = s => String(s).replace(/\|/g, '\\|');
const list = (v, max = 16) =>
  v.length <= max ? v.join(', ') : v.slice(0, max).join(', ') + ', … (' + v.length + ' values)';

function blockTable(name) {
  const B = ZC_BLOCKS[name],
    rows = [
      '| Offset | Size | Range | Init | Sent as | ID | Name | Values / unit |',
      '|---|---|---|---|---|---|---|---|'
    ];
  for (const [id, off, size, lo, hi, init, vo, label, x = {}] of B.p) {
    const kind = x.ascii ? 'ASCII' : size === 1 ? '7-bit' : size + ' nibbles';
    const sent = x.ascii ? 'text' : kind + (vo ? ', +' + vo : '');
    const vals = x.ascii ? x.ascii + ' characters' : x.v ? list(x.v) : x.u ? x.u : x.d ? 'shown ' + x.d.join('–') : '';
    rows.push(
      '| ' +
        [
          addr(off),
          size,
          x.ascii ? '' : lo + ' to ' + hi,
          x.ascii ? '' : init,
          sent,
          '`' + id + '`',
          esc(label),
          esc(vals)
        ].join(' | ') +
        ' |'
    );
  }
  return rows.join('\n');
}
function layoutTable(kind) {
  const rows = [
    '| Block | Parameters | Starts at (from the slot) | Count | Step between copies | Length |',
    '|---|---|---|---|---|---|'
  ];
  for (const [key, blk, base, n, stride] of LAYOUT[kind])
    rows.push(
      '| ' +
        [
          key,
          '[' + blk + '](#' + blk.toLowerCase() + ')',
          addr(base),
          n,
          n > 1 ? addr(stride) : '',
          ZC_BLOCKS[blk].len
        ].join(' | ') +
        ' |'
    );
  return rows.join('\n');
}
function mfxSection() {
  const out = [];
  mfxNames().forEach((name, t) => {
    const ps = mfxParams(t);
    out.push('', '### ' + t + ' ' + esc(name), '');
    if (!ps.length) {
      out.push('No parameters.');
      return;
    }
    out.push('| Slot | Name | Range |', '|---|---|---|');
    ps.forEach((sp, i) => {
      const r =
        sp.kind === 'L'
          ? sp.list === NOTES
            ? 'note: ' + list(NOTES, 30)
            : list(sp.list) + (sp.unit ? ' ' + sp.unit : '')
          : sp.lo +
            ' to ' +
            sp.hi +
            (sp.unit ? ' ' + sp.unit : '') +
            (sp.kind === 'D' ? ' (stored ×' + 10 ** sp.dec + ')' : '');
      out.push('| ' + (i + 1) + ' | ' + esc(sp.name) + ' | ' + esc(r) + ' |');
    });
  });
  return out.join('\n');
}

const toneBlocks = [...new Set(LAYOUT.tone.map(x => x[1]))],
  kitBlocks = [...new Set(LAYOUT.kit.map(x => x[1]))].filter(b => !toneBlocks.includes(b));
const doc = `# ZEN-Core parameters on the MC-707 and MC-101

<!-- generated by scripts/param-docs.mjs from src/zen/; do not edit by hand -->

Every tone, drum kit and MFX parameter the MC-707 Toolbox's ZenCore editor reads and writes over SysEx.
How to address a clip's sound, the message format and the MC-707's quirks are in
[MC707-SYSEX.md](MC707-SYSEX.md); start there.

**How to read the tables.** *Offset* is from the start of the block, as a Roland 4-byte address offset
(7 bits per byte). *Size* is the number of bytes on the wire. *Sent as*: \`7-bit\` is one byte; \`n nibbles\`
splits the value into n bytes of 4 bits, highest first; \`+k\` means the value is sent with k added
(so -100 to 100 with +128 is sent as 28 to 228). *Values* lists names from the lowest value up.

Unofficial: Roland has not published this. It comes from Roland's ZEN-Core parameter database as
decoded by [Roland-Zen-Decode-XML](https://github.com/DrKnackeratorStrikesAgain/Roland-Zen-Decode-XML),
checked against [mc-programmer](https://github.com/rsenna/mc-programmer) and
[mctools_basic](https://github.com/Locriana/mctools_basic), and tested on a real MC-707.

## Contents

- [Tone layout](#tone-layout) · ${toneBlocks.map(b => '[' + b + '](#' + b.toLowerCase() + ')').join(' · ')}
- [Drum kit layout](#drum-kit-layout) · ${kitBlocks.map(b => '[' + b + '](#' + b.toLowerCase() + ')').join(' · ')}
- [MFX types and their 32 parameter slots](#mfx-types)

## Tone layout

A tone slot holds these blocks. Blocks with a count repeat for each partial (1-4), one step apart.

${layoutTable('tone')}

## Drum kit layout

A drum kit slot. KPTL and KEQ repeat for each of the 88 keys (A0 to C8, MIDI notes 21-108).

${layoutTable('kit')}

${[...toneBlocks, ...kitBlocks].map(b => '## ' + b + '\n\n' + blockTable(b)).join('\n\n')}

## MFX types

The MFX block's \`mfxType\` picks one of these; its parameters fill \`param_1\` to \`param_32\` in this order,
each sent as 4 nibbles with 32768 added (stored -20000 to 20000). Lists are stored from 0; values with
decimals are stored multiplied (0.05-10.00 Hz is stored as 5-1000). Changing the type makes the MC-707
reset all 32 slots shortly after, so send the settings at least 300 ms later (see MC707-SYSEX.md).

${mfxSection()}
`;
const check = process.argv.includes('--check');
const old = fs.existsSync(DOC) ? fs.readFileSync(DOC, 'utf8') : '';
if (check) {
  if (old !== doc) {
    console.error('docs/ZENCORE-PARAMETERS.md is out of date. Run "node scripts/param-docs.mjs".');
    process.exit(1);
  }
  console.log('Parameter reference is up to date.');
} else {
  fs.writeFileSync(DOC, doc);
  console.log('Wrote docs/ZENCORE-PARAMETERS.md (' + Math.round(doc.length / 1024) + ' KB)');
}
