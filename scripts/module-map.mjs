// Writes the module map in docs/ARCHITECTURE.md from the header comment at the top of each module.
//
//   node scripts/module-map.mjs           update the map
//   node scripts/module-map.mjs --check   fail if the map is out of date (used in CI)
//
// Every module in src/ starts with a header: what it does, then "Owns:" and "Reads:" lines for
// shared state. Change the header and run this; never edit the generated table by hand.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { graph, layerOf } from './check-imports.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'src');
const DOC = path.join(ROOT, 'docs', 'ARCHITECTURE.md');
const START = "<!-- module-map:start (generated by scripts/module-map.mjs from each module's header) -->";
const END = '<!-- module-map:end -->';

export function header(file) {
  const lines = fs.readFileSync(file, 'utf8').split('\n');
  const out = [];
  for (const l of lines) {
    if (!l.startsWith('//')) break;
    out.push(l.replace(/^\/\/ ?/, ''));
  }
  const text = out.join('\n');
  const [purpose, rest = ''] = text.split(/\n\s*\n/);
  const owns = (/^Owns: (.*)$/m.exec(rest) || [])[1] || '';
  return { purpose: purpose.replace(/\s+/g, ' ').trim(), owns: owns.replace(/\.$/, '') };
}

export function table() {
  const g = graph();
  const files = Object.keys(g).sort();
  const order = ['core', 'library', 'services', 'clips', 'song', 'live', 'ui', 'main.js'];
  const group = f => (f.includes('/') ? f.split('/')[0] : f);
  let md = '';
  for (const grp of order) {
    const fs_ = files.filter(f => group(f) === grp);
    if (!fs_.length) continue;
    md += '\n### ' + (grp === 'main.js' ? 'main.js' : grp + '/') + ' (layer: ' + layerOf(fs_[0]) + ')\n\n';
    md += '| Module | What it does | Owns |\n| --- | --- | --- |\n';
    for (const f of fs_) {
      const h = header(path.join(SRC, f));
      if (!h.purpose) throw new Error('src/' + f + ' has no header comment');
      md += '| `' + f + '` | ' + h.purpose.replace(/\|/g, '\\|') + ' | ' + h.owns.replace(/\|/g, '\\|') + ' |\n';
    }
  }
  return md;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const doc = fs.readFileSync(DOC, 'utf8');
  const a = doc.indexOf(START),
    b = doc.indexOf(END);
  if (a < 0 || b < 0) throw new Error('docs/ARCHITECTURE.md is missing the module-map markers');
  const next = doc.slice(0, a + START.length) + '\n' + table() + '\n' + doc.slice(b);
  if (process.argv.includes('--check')) {
    if (next !== doc) {
      console.error('The module map in docs/ARCHITECTURE.md is out of date. Run "node scripts/module-map.mjs".');
      process.exit(1);
    }
    console.log('Module map is up to date.');
  } else {
    fs.writeFileSync(DOC, next);
    console.log('Updated the module map in docs/ARCHITECTURE.md');
  }
}
